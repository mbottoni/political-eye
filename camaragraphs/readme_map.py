"""An interactive vote map that lives inside the README.

GitHub runs no JavaScript in a README, but it renders ```geojson code blocks
as Azure Maps you can pan and zoom. What its renderer allows (read from
viewscreen.githubusercontent.com's geojsonMarkdown bundle, Nov 2026):

- Point features are clustered (45 px) into numbered bubbles and, once
  zoomed in, drawn as pins; clicking a pin shows its properties as a table.
- Polygons and lines are copied without their properties (no popup) and
  drawn in one fixed color; no per-feature styling is honored at all.

So each deputy is a Point, placed by the same vote PCA as the charts, over
an empty patch of the South Atlantic so the basemap stays blank. Party
color cannot be shown here; it is in the popup and in the charts.
Regenerated by `camaragraphs figures` together with the charts.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from . import graphs as g
from .figures import _orient, _positions

CENTER = (-22.0, -18.0)   # lon, lat: open ocean, no coastline or labels in view
SPAN = 8.0                # degrees from the leftmost to the rightmost deputy


ALLY_ROWS = ("Closest ally", "2nd closest", "3rd closest")


def _allies(month: str, data_dir, k: int = len(ALLY_ROWS), **kw) -> dict[int, list[str]]:
    """Each deputy's k highest-agreement partners, one short string each
    (GitHub's popup is fixed-width: one ally per row stays readable)."""
    opts = {key: v for key, v in kw.items() if key in ("min_shared", "lop", "obstruction_as_no")}
    e = g.covote_edges(month, data_dir=data_dir, **opts)
    both = pd.concat([e, e.rename(columns={"u": "v", "v": "u"})], ignore_index=True)
    both = both.sort_values(["u", "agreement", "n_shared", "v"], ascending=[True, False, False, True])
    names = g.load_month(month, data_dir).deputies.set_index("deputado_id")
    return {
        int(u): [f"{names.at[int(r.v), 'nome']} ({names.at[int(r.v), 'partido']}, {r.agreement:.0%})"
                 for r in grp.head(k).itertuples()]
        for u, grp in both.groupby("u", sort=False)
    }


def feature_collection(month: str, data_dir=None, **kw) -> dict:
    gv = g.graph(month, "covote", data_dir=data_dir, **kw)
    gc = g.graph(month, "cosponsor", data_dir=data_dir, **kw)
    nodes = list(gv.nodes)
    parties = [gv.nodes[n].get("party", "") for n in nodes]
    P = _orient(_positions(month, nodes, data_dir, **kw), parties)
    span = float(np.ptp(P[:, 0])) or 1.0
    scale = SPAN / span
    lon = CENTER[0] + (P[:, 0] - P[:, 0].mean()) * scale
    lat = CENTER[1] + (P[:, 1] - P[:, 1].mean()) * scale
    allies = _allies(month, data_dir, **kw)
    feats = []
    for i, n in enumerate(nodes):
        a = gv.nodes[n]
        feats.append({
            "type": "Feature",
            "properties": {
                "Deputy": a.get("name", str(n)),
                "Party": f"{a.get('party', '')} · {a.get('uf', '')}",
                "Votes alike with": f"{gv.degree(n)} deputies",
                "Co-signed with": f"{gc.degree(n) if n in gc else 0} deputies",
                **dict(zip(ALLY_ROWS, allies.get(n, []))),
            },
            "geometry": {"type": "Point", "coordinates": [round(float(lon[i]), 4), round(float(lat[i]), 4)]},
        })
    return {"type": "FeatureCollection", "features": feats}


def block(month: str, data_dir=None, **kw) -> str:
    fc = feature_collection(month, data_dir, **kw)
    lines = ",\n".join(json.dumps(f, ensure_ascii=False, separators=(",", ":")) for f in fc["features"])
    caption = (
        f"**{month}, {len(fc['features'])} deputies.** Each pin is a deputy, placed by how they voted: the "
        f"government side is on the left and the opposition on the right. Nearby pins merge into numbered "
        f"bubbles until you zoom in. Click a pin to see the deputy's party, how many deputies they vote alike "
        f"with (agreeing on at least {g.TAU:.0%} of shared votes) and sign with, and their closest allies. "
        f"GitHub's maps can't be colored, so parties are shown in the charts below. The water is only the map "
        f"background."
    )
    return f"{caption}\n\n```geojson\n{{\"type\":\"FeatureCollection\",\"features\":[\n{lines}\n]}}\n```"


def update_readme(readme: Path, month: str, data_dir=None, **kw) -> None:
    text = readme.read_text()
    pat = re.compile(r"(<!-- BEGIN:MAP -->\n).*?(<!-- END:MAP -->)", re.S)
    if not pat.search(text):
        raise ValueError("README.md is missing the MAP markers")
    body = block(month, data_dir, **kw)
    readme.write_text(pat.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text))
